/**
 * Геометрия стрелок перешвартовок для svg-оверлея «Постановки судов».
 *
 * Здесь только чистые вычисления: путь, наконечник, кружок старта и место
 * подписи. React-а нет намеренно — страницу-сетку и так нелегко читать, а эти
 * формулы хочется менять, глядя на одну короткую функцию (и проверять без
 * браузера). Ничего из этого не влияет на то, ЧТО создаётся и сохраняется:
 * только на то, КАК стрелка выглядит.
 */

/**
 * Якорь стрелки: горизонтальное «дыхание» полосы (её левый и правый край) и
 * середина по вертикали. Координаты — в пикселях холста `[data-vp-print]`,
 * поэтому оверлей скроллится вместе с сеткой и стрелки не разъезжаются.
 */
export type ArrowAnchor = { left: number; right: number; y: number };

export type ArrowGeom = {
  /** прямая «из пункта А в пункт Б»: от ближнего торца оригинала к ближнему торцу копии */
  d: string;
  /** начало: сюда встаёт кружок «откуда» */
  startX: number;
  startY: number;
  /** наконечник: сюда смотрит стрелка и рядом ложится подпись «куда» */
  tipX: number;
  tipY: number;
  /** куда смотрит стрелка по горизонтали — от него зависит, какой стороной класть подпись */
  rightward: boolean;
};


const n = (v: number) => Math.round(v * 100) / 100;

/**
 * Стрелка — прямая линия: от ближнего торца оригинала к ближнему торцу копии.
 *
 * Ортогональная «ёлочка» (горизонталь → вертикаль → горизонталь) была ближе к
 * тому, как диспетчеры рисуют в Excel, но на сетке причалов она резала чужие
 * строки, и стрелки разных цепочек путались между собой. Прямая читается
 * коротко: начало, конец, направление. Начало задаёт кружок «откуда», конец —
 * наконечник, а «что за шаг» дописывает подпись у острия.
 *
 * Берём ближние стороны полос: стрелка упирается в торец копии, а не
 * перелетает через неё и не стартует из середины исходной полосы.
 */
export function arrowGeometry(a: ArrowAnchor, b: ArrowAnchor): ArrowGeom {
  const rightward = b.left >= a.left;
  const startX = rightward ? a.right : a.left;
  const tipX = rightward ? b.left : b.right;
  return {
    d: `M ${n(startX)} ${n(a.y)} L ${n(tipX)} ${n(b.y)}`,
    startX,
    startY: a.y,
    tipX,
    tipY: b.y,
    rightward,
  };
}

/** Где лежит подпись у наконечника. */
export type ArrowLabel = { x: number; y: number; anchor: "start" | "end" };

/**
 * Подпись ставим НАД наконечником — там, где она
 * объясняет стрелку, а не висит в пустоте. Метрик текста у svg-подписи нет,
 * поэтому ширину прикидываем по числу знаков: подпись короткая
 * («шаг 1→2 · РП-6 · 02.11 12:00»), и запаса хватает, чтобы не вылезти за край.
 *
 * Оверлей sized по холсту и обрезан по нему, так что «вылезти» означает
 * «обрезаться», а не «добавить горизонтальный скролл». Тем не менее у правого
 * края подпись разворачиваем влево — там, где есть место.
 */
export function arrowLabel(
  text: string,
  geom: ArrowGeom,
  canvasW: number,
  fontSize = 10.5,
): ArrowLabel {
  const width = text.length * fontSize * 0.58;
  const w = canvasW > 0 ? canvasW : Number.MAX_SAFE_INTEGER;
  // над путём; у самого верха холста — под путём, иначе обрежется шапкой
  const y = geom.tipY - 5 > fontSize ? n(geom.tipY - 5) : n(geom.tipY + fontSize + 3);
  // стрелка вправо приходит слева → свободный горизонтальный участок слева от наконечника
  let anchor: "start" | "end" = geom.rightward ? "end" : "start";
  let x = geom.rightward ? geom.tipX - 5 : geom.tipX + 5;
  if (anchor === "start" && x + width > w - 2) {
    anchor = "end"; // правый край: кладём слева от наконечника
    x = geom.tipX - 5;
  } else if (anchor === "end" && x - width < 2) {
    anchor = "start"; // левый край (стрелка идёт влево и уперлась в начало холста)
    x = geom.tipX + 5;
  }
  return { x: n(x), y, anchor };
}
